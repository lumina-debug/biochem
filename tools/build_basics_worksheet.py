def render_item(text: str, key: bool) -> str:
    """{{答え}} を空欄または解答に変換する。"""
    parts = []
    pos = 0
    for m in re.finditer(r"\{\{(.+?)\}\}", text):
        parts.append(html.escape(text[pos:m.start()]))
        ans = m.group(1)
        if key:
            parts.append('<span class="b">%s</span>' % html.escape(ans))
        else:
            n = len(ans)
            cls = "b s" if n <= 3 else ("b l" if n >= 12 else "b")
            parts.append('<span class="%s">&nbsp;</span>' % cls)
        pos = m.end()
    parts.append(html.escape(text[pos:]))
    return "".join(parts)


def render_sections(key: bool) -> str:
    out = []
    for letter, title, items in SECTIONS:
        out.append('<section class="ws-sec">')
        out.append('  <h3>%s．%s</h3>' % (letter, html.escape(title)))
        out.append('  <ol class="ws-list">')
        for it in items:
            out.append('    <li>%s</li>' % render_item(it, key))
        out.append('  </ol>')
        out.append('</section>')
    return "\n".join(out)


